// Picks an icon for a diagram box from its label, so hand-written topics get
// sensible icons without listing one per box. First match wins.
const RULES: [RegExp, LucideIcon][] = [
  [/forbidden|unauthori[sz]ed|\b40[13]\b/i, ShieldX],
  [/database|\bdb\b|store|postgres|sql|snapshot/i, Database],
  [/driver app|rider app|client app|mobile|phone/i, Smartphone],
  [/user|browser|rider|maya/i, User],
  [/load balancer|\blb\b|nginx/i, Network],
  [/gateway/i, ShieldCheck],
  [/bank|\bupi\b/i, Landmark],
  [/webhook/i, Webhook],
  [/reconcil/i, Scale],
  [/internet|wi-fi|\b4g\b/i, Globe],
  [/cache|redis/i, Zap],
  [/kafka|queue|stream|event/i, ListOrdered],
  [/key|token|jwt/i, KeyRound],
  [/login|auth|identity|policy|permission/i, LockKeyhole],
  [/audit|log/i, ScrollText],
  [/forecast|pric|surge|multiplier/i, TrendingUp],
  [/heatmap|map|h3|hexagon/i, MapIcon],
  [/smooth|average/i, Activity],
  [/drop-off|detect/i, Gauge],
  [/quote/i, Receipt],
  [/worker|processor|generator|engine/i, Cog],
  [/hypervisor|hardware/i, Cpu],
  [/os\b|kernel|guest/i, HardDrive],
  [/namespace|cgroup/i, Layers],
  [/container/i, Container],
  [/image|layers/i, Boxes],
  [/registry/i, Warehouse],
  [/dockerfile/i, FileCode],
  [/app|service|api|server|dispatch/i, Server],
  [/browser|client/i, MonitorSmartphone],
]

export function iconFor(label: string): LucideIcon {
  return RULES.find(([pattern]) => pattern.test(label))?.[1] ?? Box
}
